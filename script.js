document.addEventListener('DOMContentLoaded', () => {
  // Restore saved language or default to 'id'
  const savedLang = localStorage.getItem('ibs_language') || 'id';
  setLanguage(savedLang);

  const modals = ['videoModal', 'registerModal', 'searchModal'];
  modals.forEach((id) => {
    const modal = document.getElementById(id);
    if (modal) {
      modal.addEventListener('click', (e) => {
        if (e.target === modal) {
          if (id === 'videoModal') closeVideoModal();
          if (id === 'registerModal') closeRegisterModal();
          if (id === 'searchModal') closeSearchModal();
        }
      });
    }
  });
});
