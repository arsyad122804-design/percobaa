// ENHANCED VIDEO PLAYER MODAL (YOUTUBE & MP4 SUPPORT)
// -------------------------------------------------------------
function extractYouTubeId(urlOrId) {
  if (!urlOrId) return null;
  if (/^[a-zA-Z0-9_-]{11}$/.test(urlOrId)) return urlOrId;
  const match = urlOrId.match(/(?:youtu\.be\/|youtube\.com\/(?:embed\/|v\/|watch\?v=|watch\?.+&v=|shorts\/))([\w-]{11})/);
  return match ? match[1] : null;
}

function playVideo(title, videoSrc = 'assets/video-profile.mp4', duration = '') {
  const modal = document.getElementById('videoModal');
  const titleElem = document.getElementById('videoModalTitle');
  const container = document.getElementById('videoContainer');

  if (titleElem) {
    titleElem.innerText = duration ? `${title} (${duration})` : title;
  }

  const ytId = extractYouTubeId(videoSrc);

  if (container) {
    if (ytId) {
      container.innerHTML = `
        <iframe class="w-full h-full rounded-2xl sm:rounded-3xl" src="https://www.youtube.com/embed/${ytId}?autoplay=1&rel=0&modestbranding=1" title="${title}" frameborder="0" allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share" allowfullscreen></iframe>
      `;
    } else {
      const src = (videoSrc && videoSrc.endsWith('.mp4')) ? videoSrc : 'assets/video-profile.mp4';
      container.innerHTML = `
        <video id="modalVideoPlayer" controls autoplay playsinline loop class="w-full h-full object-cover bg-black rounded-2xl sm:rounded-3xl">
          <source src="${src}" type="video/mp4">
          Browser Anda tidak mendukung pemutaran video MP4.
        </video>
      `;
    }
  }

  if (modal) {
    modal.classList.remove('hidden');
    document.body.style.overflow = 'hidden';
  }
}

function closeVideoModal() {
  const modal = document.getElementById('videoModal');
  const container = document.getElementById('videoContainer');
  
  if (container) {
    // Clear innerHTML to stop YouTube iframe / HTML5 video playback immediately
    container.innerHTML = '';
  }

  if (modal) {
    modal.classList.add('hidden');
    document.body.style.overflow = 'auto';
  }
}

