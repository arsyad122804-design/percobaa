function toggleLangDropdown(e) {
  if (e) e.stopPropagation();
  const menu = document.getElementById('langMenu');
  const arrow = document.getElementById('langArrow');
  if (menu) {
    const isHidden = menu.classList.toggle('hidden');
    if (arrow) {
      arrow.style.transform = isHidden ? 'rotate(0deg)' : 'rotate(180deg)';
    }
  }
}

function closeLangDropdown() {
  const menu = document.getElementById('langMenu');
  const arrow = document.getElementById('langArrow');
  if (menu) {
    menu.classList.add('hidden');
  }
  if (arrow) {
    arrow.style.transform = 'rotate(0deg)';
  }
}

function setLanguage(lang) {
  if (!TRANSLATIONS[lang]) return;
  currentLang = lang;
  localStorage.setItem('ibs_language', lang);

  // Set HTML dir and lang attributes
  const html = document.documentElement;
  html.setAttribute('lang', lang);
  if (lang === 'ar') {
    html.setAttribute('dir', 'rtl');
  } else {
    html.setAttribute('dir', 'ltr');
  }

  // Update navbar flag & label
  const flagContainer = document.getElementById('currentFlag');
  const langLabel = document.getElementById('currentLangLabel');
  if (flagContainer) flagContainer.innerHTML = FLAG_ICONS[lang] || FLAG_ICONS.id;
  if (langLabel) langLabel.innerText = TRANSLATIONS[lang].lang_code;

  // Update checkmarks in dropdown
  ['id', 'en', 'ar'].forEach(l => {
    const check = document.querySelector(`.checkmark-${l}`);
    if (check) {
      if (l === lang) check.classList.remove('hidden');
      else check.classList.add('hidden');
    }
    const mobileBtn = document.querySelector(`.mobile-lang-${l}`);
    if (mobileBtn) {
      if (l === lang) {
        mobileBtn.className = `mobile-lang-${l} px-3 py-1 rounded-full text-xs font-bold bg-white text-slate-900 shadow-sm`;
      } else {
        mobileBtn.className = `mobile-lang-${l} px-3 py-1 rounded-full text-xs font-medium text-white/80 hover:bg-white/10`;
      }
    }
  });

  // Apply translations to all DOM elements with data-i18n
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key] !== undefined) {
      el.innerHTML = TRANSLATIONS[lang][key];
    }
  });

  // Apply placeholders
  const placeholderElements = document.querySelectorAll('[data-i18n-ph]');
  placeholderElements.forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key] !== undefined) {
      el.setAttribute('placeholder', TRANSLATIONS[lang][key]);
    }
  });

  closeLangDropdown();
}

